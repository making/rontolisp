#!/usr/bin/env python3
"""Generate src/budoux-ja.lisp from BudouX's Japanese model.

    curl -sSfLO https://raw.githubusercontent.com/google/budoux/<sha>/budoux/models/ja.json
    python3 tools/gen-budoux.py ja.json <sha> > src/budoux-ja.lisp

Each feature group becomes one string of space-separated key/weight pairs, decoded once
at run time: a string constant compiles far smaller than 1,600 consed literals.
"""
import json
import sys

GROUPS = ["UW1", "UW2", "UW3", "UW4", "UW5", "UW6", "BW1", "BW2", "BW3", "TW1", "TW2", "TW3", "TW4"]


def main():
    path, sha = sys.argv[1], sys.argv[2]
    with open(path, encoding="utf-8") as f:
        model = json.load(f)
    for group in model.values():
        for key in group:
            if any(c in key for c in ' \t\n"\\'):
                sys.exit("unexpected character in key %r" % key)
    total = sum(sum(g.values()) for g in model.values())
    out = sys.stdout
    out.write(";;;; budoux-ja.lisp -- BudouX's Japanese phrase model as data.\n")
    out.write(";;;;\n")
    out.write(";;;; Generated by tools/gen-budoux.py from google/budoux %s\n" % sha)
    out.write(";;;; budoux/models/ja.json. Do not edit by hand.\n")
    out.write(";;;; Copyright 2021 Google LLC. Licensed under the Apache License 2.0\n")
    out.write(";;;; (tools/BUDOUX-LICENSE).\n\n")
    out.write("(in-package :lispresen)\n\n")
    out.write(";;; The sum of every weight; a position breaks when 2 x its score exceeds it.\n")
    out.write("(defparameter *budoux-ja-total* %d)\n\n" % total)
    out.write(";;; One string per feature group, in the order UW1..UW6 BW1..BW3 TW1..TW4.\n")
    out.write("(defparameter *budoux-ja-groups*\n  (list\n")
    for name in GROUPS:
        pairs = " ".join("%s %d" % (k, v) for k, v in sorted(model.get(name, {}).items()))
        out.write('   "%s"\n' % pairs)
    out.write("   ))\n")


if __name__ == "__main__":
    main()
