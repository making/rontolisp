package am.ik.rontolisp.cli;

import java.io.PrintStream;
import java.nio.file.Files;
import java.nio.file.Path;

import am.ik.rontolisp.eval.SourceLanguage;
import am.ik.rontolisp.eval.SourceLoader;
import org.jspecify.annotations.Nullable;

/**
 * The {@code rontolisp build} subcommand: {@code asdf:make} of an ASDF system whose
 * {@code :build-operation} is {@code program-op} (or a subclass, deploy's
 * {@code deploy-op}), from the command line -- the spelling of
 * {@code sbcl --eval '(asdf:make :app)'}.
 * <p>
 * The command GENERATES a program and INTERPRETS it: the interpreter is the image the
 * build runs in, so a library's build-time work (deploy's hooks) runs there as it runs in
 * SBCL's image, and the dump compiles the image ({@code uiop:dump-image}, the
 * interpreter's {@code ImageBuilder}). What the command line adds over a plain
 * {@code asdf:make} is the artifact's compile flags, which reach that dump, and
 * {@code -o}, which replaces the system's build pathname for the build. Where the
 * artifact goes and what it is follows that pathname: no type is a native executable,
 * {@code .jar} or {@code .class} a JVM program, {@code .wasm} a module.
 */
final class BuildCommand {

	private BuildCommand() {
	}

	/**
	 * The generated program and the directory its relative paths resolve against.
	 *
	 * @param source the program text
	 * @param baseDir the {@code .asd}'s directory for a {@code .asd} target, else
	 * {@code null} (the working directory)
	 */
	record Program(String source, @Nullable String baseDir) {
	}

	/**
	 * Builds the program for the given command line.
	 * @param options the options after the {@code build} subcommand name
	 * @return the program, or {@code null} when the command line was wrong -- the message
	 * is already on standard error and the caller exits 2
	 */
	@Nullable static Program build(CliOptions options) {
		String target = options.getNokey();
		if (options.clojureRun() != null || options.contains("-A")) {
			return fail("the deps.edn aliases select a Clojure run, and build makes an ASDF system's executable");
		}
		if (options.contains("-e")) {
			return fail("-e/--eval names a program, not a system: give the system's name or its .asd");
		}
		if (target == null) {
			return fail("no system given (try: rontolisp build --help)");
		}
		if (!options.arguments().isEmpty()) {
			return fail("'--' passes arguments to a program, and build runs none: pass them to the executable");
		}
		String name = target;
		String asd = null;
		Path path = Path.of(target);
		if (target.endsWith(".asd")) {
			if (!Files.isRegularFile(path)) {
				return fail(target + ": no such file");
			}
			asd = path.toAbsolutePath().toString();
			String file = path.getFileName().toString();
			name = file.substring(0, file.length() - ".asd".length());
		}
		else if (SourceLanguage.isSourceFile(target) || Files.isDirectory(path)) {
			return fail(target + " is no system: give the system's name or its .asd");
		}
		StringBuilder out = new StringBuilder();
		out.append(";;; Generated by `rontolisp build`: asdf:make of the system, whose program-op\n");
		out.append(";;; dumps the image this program runs in.\n");
		if (asd != null) {
			out.append("(asdf:load-asd ").append(string(asd)).append(")\n");
		}
		out.append("(asdf:load-system ").append(string(name)).append(")\n");
		out.append("(let* ((system (asdf:find-system ").append(string(name)).append("))\n");
		out.append("       (operation (%asdf-build-operation system)))\n");
		out.append("  (unless (typep operation 'asdf:image-op)\n");
		// ~a with the name as an ARGUMENT, never spliced into the control string.
		out.append("    (error \"rontolisp build: ~a builds no executable: its :build-operation is ~(~a~),"
				+ " so asdf:make only loads it -- a program declares :build-operation \\\"program-op\\\""
				+ " and an :entry-point\"\n");
		out.append("           ").append(string(name)).append(" (class-name (class-of operation))))\n");
		String output = options.get("-o");
		if (output != null) {
			out.append("  (setf (asdf::component-build-pathname system) (pathname ")
				.append(string(Path.of(output).toAbsolutePath().normalize().toString()))
				.append("))\n");
		}
		out.append("  (asdf:make system))\n");
		return new Program(out.toString(),
				asd == null ? null : SourceLoader.parentDir(Path.of(asd).toAbsolutePath().toString()));
	}

	/** A Lisp string literal for the given text. */
	private static String string(String text) {
		return "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
	}

	@Nullable private static Program fail(String message) {
		System.err.println("rontolisp: build: " + message);
		return null;
	}

	static void printUsage(PrintStream out) {
		out.println("Usage: rontolisp build [options] SYSTEM|FILE.asd");
		out.println();
		out.println("Builds the executable an ASDF system declares -- asdf:make of a system");
		out.println("whose :build-operation is \"program-op\" (or deploy's \"deploy-op\"), with");
		out.println("its :entry-point as the program and :build-pathname naming the artifact.");
		out.println("The system loads on the interpreter, which is the image the build runs");
		out.println("in; the image is then compiled. The artifact's type follows its name:");
		out.println("no type is a native executable, .jar or .class a JVM program, .wasm a");
		out.println("WASI module.");
		out.println();
		out.println("Targets:");
		out.println("  SYSTEM             An ASDF system on the search path (the working");
		out.println("                     directory, --system-path, RONTOLISP_SOURCE_REGISTRY)");
		out.println("  FILE.asd           The system the .asd is named after");
		out.println();
		out.println("Options:");
		out.println("  -o FILE            Write the artifact here instead of at the system's");
		out.println("                     :build-pathname; its type decides what it is");
		out.println("  --native-target T  The platform of a native executable");
		out.println("  --native-cpu L     Its CPU level (baseline, host, x86-64-v3, ...)");
		out.println("  --component        A .wasm as a WASI 0.3 component");
		out.println("  --optimize=LEVEL   As for -o: off, speed (default), size");
		out.println("  --system-path DIRS Directories searched for NAME.asd (like PATH)");
		out.println("  --dist DISTS       Dists ql:quickload may download from");
		out.println("  --feature NAMES    Read-time features to add");
		out.println("  -h, --help         Show this help message");
		out.println();
		out.println("Every other compiler flag reaches the compile as it does with -o.");
	}

}
