package am.ik.jdbc.postgresql;

import java.sql.ClientInfoStatus;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLClientInfoException;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Savepoint;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

import org.jspecify.annotations.Nullable;

/**
 * A connection: one session with the server and what JDBC keeps of it -- whether each
 * statement is a transaction of its own, and the transaction that is open otherwise,
 * which starts with the first statement after the last one ended.
 */
final class PostgresConnection extends UnsupportedConnection {

	private final Session session;

	private boolean autoCommit = true;

	private boolean readOnly;

	private int savepoints;

	private @Nullable SQLWarning warnings;

	// The names of the types the driver does not tell apart, as the catalog gave them.
	private final Map<Integer, String> typeNames = new HashMap<>();

	PostgresConnection(Session session) {
		this.session = session;
		this.warnings = session.takeWarnings();
	}

	/** The session, for a statement to run on. */
	Session session() throws SQLException {
		open();
		return this.session;
	}

	private void open() throws SQLException {
		if (this.session.isClosed()) {
			throw Failures.closed("connection");
		}
	}

	// Runs a statement of the connection's own, outside the transaction JDBC keeps.
	private List<Result> run(String sql) throws SQLException {
		open();
		List<Result> results = new ArrayList<>();
		synchronized (this.session) {
			this.session.simple(sql);
			this.session.run(results, 0, false);
		}
		return results;
	}

	/**
	 * The rows of a query of the connection's own, run outside the transaction JDBC keeps
	 * when none is open.
	 */
	ResultSet query(String sql) throws SQLException {
		return new PostgresResultSet(null, this, run(sql).get(0), ResultSet.TYPE_FORWARD_ONLY);
	}

	// The one value a statement of the connection's own answers.
	private @Nullable String value(String sql) throws SQLException {
		try (ResultSet rows = query(sql)) {
			return rows.next() ? rows.getString(1) : null;
		}
	}

	/**
	 * The server's name of a type, asked of the catalog once for one the driver does not
	 * tell apart.
	 */
	String typeName(int type) throws SQLException {
		String name = TypeId.name(type);
		if (name != null) {
			return name;
		}
		synchronized (this.session) {
			name = this.typeNames.get(type);
			if (name == null) {
				name = value("SELECT typname FROM pg_catalog.pg_type WHERE oid = " + Integer.toUnsignedString(type));
				name = name != null ? name : Integer.toUnsignedString(type);
				this.typeNames.put(type, name);
			}
			return name;
		}
	}

	// Statements.

	@Override
	public Statement createStatement() throws SQLException {
		return createStatement(ResultSet.TYPE_FORWARD_ONLY, ResultSet.CONCUR_READ_ONLY);
	}

	@Override
	public Statement createStatement(int type, int concurrency) throws SQLException {
		open();
		return new PostgresStatement(this, kind(type, concurrency));
	}

	@Override
	public Statement createStatement(int type, int concurrency, int holdability) throws SQLException {
		return createStatement(type, concurrency);
	}

	@Override
	public PreparedStatement prepareStatement(String sql) throws SQLException {
		return prepare(sql, ResultSet.TYPE_FORWARD_ONLY, null);
	}

	@Override
	public PreparedStatement prepareStatement(String sql, int type, int concurrency) throws SQLException {
		return prepare(sql, kind(type, concurrency), null);
	}

	@Override
	public PreparedStatement prepareStatement(String sql, int type, int concurrency, int holdability)
			throws SQLException {
		return prepare(sql, kind(type, concurrency), null);
	}

	@Override
	public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
		return prepare(sql, ResultSet.TYPE_FORWARD_ONLY,
				autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS ? new String[0] : null);
	}

	@Override
	public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
		return prepare(sql, ResultSet.TYPE_FORWARD_ONLY, columnNames);
	}

	private PreparedStatement prepare(String sql, int type, String @Nullable [] keyColumns) throws SQLException {
		open();
		if (sql == null) {
			throw new SQLException("The statement is null", "42601");
		}
		return new PostgresPreparedStatement(this, type, sql, keyColumns);
	}

	// A result set holds its rows: it can be walked both ways, sees no change and makes
	// none.
	private static int kind(int type, int concurrency) throws SQLException {
		if (type == ResultSet.TYPE_SCROLL_SENSITIVE) {
			throw Failures.unsupported("A result set that sees the changes of others");
		}
		if (concurrency != ResultSet.CONCUR_READ_ONLY) {
			throw Failures.unsupported("A result set that updates its rows");
		}
		return type;
	}

	/**
	 * The JDBC escapes in braces are not read: a statement goes to the server as it is.
	 */
	@Override
	public String nativeSQL(String sql) throws SQLException {
		open();
		return sql;
	}

	// Transactions.

	@Override
	public boolean getAutoCommit() throws SQLException {
		open();
		return this.autoCommit;
	}

	@Override
	public void setAutoCommit(boolean autoCommit) throws SQLException {
		open();
		if (autoCommit != this.autoCommit && this.session.inTransaction()) {
			end("COMMIT");
		}
		this.autoCommit = autoCommit;
	}

	@Override
	public void commit() throws SQLException {
		manual("commit");
		if (this.session.inTransaction()) {
			List<Result> results = end("COMMIT");
			if (!results.isEmpty() && "ROLLBACK".equals(results.get(0).tag)) {
				throw Failures.of("The transaction had failed and was rolled back, not committed", "40000");
			}
		}
	}

	@Override
	public void rollback() throws SQLException {
		manual("rollback");
		if (this.session.inTransaction()) {
			end("ROLLBACK");
		}
	}

	private void manual(String what) throws SQLException {
		open();
		if (this.autoCommit) {
			throw new SQLException("A " + what + " of a connection that commits each statement", "25000");
		}
	}

	private List<Result> end(String command) throws SQLException {
		this.savepoints = 0;
		return run(command);
	}

	@Override
	public Savepoint setSavepoint() throws SQLException {
		manual("savepoint");
		return savepoint(new PostgresSavepoint(++this.savepoints, null));
	}

	@Override
	public Savepoint setSavepoint(String name) throws SQLException {
		manual("savepoint");
		if (name == null) {
			throw new SQLException("The savepoint's name is null", "3B001");
		}
		return savepoint(new PostgresSavepoint(0, name));
	}

	private Savepoint savepoint(PostgresSavepoint savepoint) throws SQLException {
		List<Result> results = new ArrayList<>();
		synchronized (this.session) {
			this.session.transaction();
			this.session.simple("SAVEPOINT " + savepoint.identifier());
			this.session.run(results, 0, false);
		}
		return savepoint;
	}

	@Override
	public void rollback(Savepoint savepoint) throws SQLException {
		manual("rollback");
		run("ROLLBACK TO SAVEPOINT " + own(savepoint).identifier());
	}

	@Override
	public void releaseSavepoint(Savepoint savepoint) throws SQLException {
		open();
		run("RELEASE SAVEPOINT " + own(savepoint).identifier());
	}

	private static PostgresSavepoint own(Savepoint savepoint) throws SQLException {
		if (savepoint instanceof PostgresSavepoint own) {
			return own;
		}
		throw new SQLException("The savepoint is not one of this driver's", "3B001");
	}

	@Override
	public int getTransactionIsolation() throws SQLException {
		String level = value("SHOW transaction_isolation");
		return switch (level != null ? level : "") {
			case "read uncommitted" -> Connection.TRANSACTION_READ_UNCOMMITTED;
			case "repeatable read" -> Connection.TRANSACTION_REPEATABLE_READ;
			case "serializable" -> Connection.TRANSACTION_SERIALIZABLE;
			default -> Connection.TRANSACTION_READ_COMMITTED;
		};
	}

	@Override
	public void setTransactionIsolation(int level) throws SQLException {
		String name = switch (level) {
			case Connection.TRANSACTION_READ_UNCOMMITTED -> "READ UNCOMMITTED";
			case Connection.TRANSACTION_READ_COMMITTED -> "READ COMMITTED";
			case Connection.TRANSACTION_REPEATABLE_READ -> "REPEATABLE READ";
			case Connection.TRANSACTION_SERIALIZABLE -> "SERIALIZABLE";
			default -> throw new SQLException("No transaction isolation level is " + level, "22023");
		};
		between("isolation level");
		run("SET SESSION CHARACTERISTICS AS TRANSACTION ISOLATION LEVEL " + name);
	}

	@Override
	public boolean isReadOnly() throws SQLException {
		open();
		return this.readOnly;
	}

	@Override
	public void setReadOnly(boolean readOnly) throws SQLException {
		between("read-only mode");
		if (readOnly != this.readOnly) {
			run("SET SESSION CHARACTERISTICS AS TRANSACTION " + (readOnly ? "READ ONLY" : "READ WRITE"));
			this.readOnly = readOnly;
		}
	}

	private void between(String what) throws SQLException {
		open();
		if (this.session.inTransaction()) {
			throw new SQLException("The " + what + " cannot change inside a transaction", "25001");
		}
	}

	@Override
	public int getHoldability() throws SQLException {
		open();
		return ResultSet.HOLD_CURSORS_OVER_COMMIT;
	}

	@Override
	public void setHoldability(int holdability) throws SQLException {
		open();
		if (holdability != ResultSet.HOLD_CURSORS_OVER_COMMIT) {
			throw Failures.unsupported("A result set that closes at a commit");
		}
	}

	// The connection itself.

	@Override
	public void close() throws SQLException {
		synchronized (this.session) {
			this.session.close();
		}
	}

	@Override
	public boolean isClosed() throws SQLException {
		return this.session.isClosed();
	}

	@Override
	public void abort(Executor executor) throws SQLException {
		this.session.abort();
	}

	/**
	 * Asks the server an empty query.
	 * @param timeout the seconds to wait for its answer, 0 for as long as it takes
	 */
	@Override
	public boolean isValid(int timeout) throws SQLException {
		if (timeout < 0) {
			throw new SQLException("The seconds to wait cannot be negative: " + timeout, "22023");
		}
		if (this.session.isClosed()) {
			return false;
		}
		synchronized (this.session) {
			try {
				int kept = this.session.timeout();
				this.session.timeout(timeout * 1000);
				this.session.simple("");
				this.session.run(null, 0, false);
				this.session.timeout(kept);
				return true;
			}
			catch (SQLException ex) {
				return false;
			}
		}
	}

	@Override
	public DatabaseMetaData getMetaData() throws SQLException {
		open();
		return new PostgresDatabaseMetaData(this, this.session);
	}

	@Override
	public String getCatalog() throws SQLException {
		open();
		return this.session.target().database;
	}

	/**
	 * A session is of one database: another cannot be chosen, and the request is ignored.
	 */
	@Override
	public void setCatalog(String catalog) throws SQLException {
		open();
	}

	@Override
	public @Nullable String getSchema() throws SQLException {
		return value("SELECT current_schema()");
	}

	@Override
	public void setSchema(String schema) throws SQLException {
		run(schema == null ? "RESET search_path" : "SET search_path TO " + Sql.identifier(schema));
	}

	@Override
	public @Nullable SQLWarning getWarnings() throws SQLException {
		open();
		return this.warnings;
	}

	@Override
	public void clearWarnings() throws SQLException {
		open();
		this.warnings = null;
	}

	@Override
	public Map<String, Class<?>> getTypeMap() throws SQLException {
		open();
		return new HashMap<>();
	}

	@Override
	public void setTypeMap(Map<String, Class<?>> map) throws SQLException {
		open();
		if (map != null && !map.isEmpty()) {
			throw Failures.unsupported("A type map");
		}
	}

	/** The milliseconds a read from the server waits; 0 for as long as it takes. */
	@Override
	public int getNetworkTimeout() throws SQLException {
		open();
		return this.session.timeout();
	}

	@Override
	public void setNetworkTimeout(Executor executor, int milliseconds) throws SQLException {
		open();
		if (milliseconds < 0) {
			throw new SQLException("The milliseconds to wait cannot be negative: " + milliseconds, "22023");
		}
		this.session.timeout(milliseconds);
	}

	// The one client info property is the name the server shows for the session.

	@Override
	public @Nullable String getClientInfo(String name) throws SQLException {
		open();
		return "ApplicationName".equals(name) ? this.session.parameter("application_name") : null;
	}

	@Override
	public Properties getClientInfo() throws SQLException {
		Properties info = new Properties();
		String application = getClientInfo("ApplicationName");
		if (application != null) {
			info.setProperty("ApplicationName", application);
		}
		return info;
	}

	@Override
	public void setClientInfo(String name, String value) throws SQLClientInfoException {
		try {
			if (!"ApplicationName".equals(name)) {
				throw new SQLException("No client info property is named " + name, "22023");
			}
			open();
			// The value goes apart from the text, so nothing in it is read as SQL.
			synchronized (this.session) {
				this.session.parse("SELECT pg_catalog.set_config('application_name', $1, false)",
						new int[] { TypeId.TEXT });
				this.session.bind(new String[] { value != null ? value : "" }, false, 0);
				this.session.sync();
				this.session.run(null, 0, false);
			}
		}
		catch (SQLException ex) {
			Map<String, ClientInfoStatus> failed = new HashMap<>();
			failed.put(name, "ApplicationName".equals(name) ? ClientInfoStatus.REASON_UNKNOWN
					: ClientInfoStatus.REASON_UNKNOWN_PROPERTY);
			throw new SQLClientInfoException(ex.getMessage(), ex.getSQLState(), failed, ex);
		}
	}

	@Override
	public void setClientInfo(Properties properties) throws SQLClientInfoException {
		if (properties != null) {
			for (String name : properties.stringPropertyNames()) {
				setClientInfo(name, properties.getProperty(name));
			}
		}
	}

}
