package am.ik.jdbc.postgresql;

import java.sql.BatchUpdateException;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import org.jspecify.annotations.Nullable;

/**
 * A statement run through the simple query: its text goes to the server as it is, so it
 * may hold several commands, each answering a result.
 */
class PostgresStatement extends UnsupportedStatement {

	final PostgresConnection connection;

	private final int resultSetType;

	private boolean closed;

	// What the last run answered, and the result getResultSet and getUpdateCount speak
	// of.
	final List<Result> results = new ArrayList<>();

	private int current;

	// The result set made of the current result, once asked for.
	private @Nullable PostgresResultSet resultSet;

	// The rows the last run wrote, when they were asked for.
	private @Nullable Result keys;

	private @Nullable SQLWarning warnings;

	private int maxRows;

	private int fetchSize;

	private int timeoutSeconds;

	private boolean closeOnCompletion;

	private boolean poolable;

	private final List<String> batch = new ArrayList<>();

	PostgresStatement(PostgresConnection connection, int resultSetType) {
		this.connection = connection;
		this.resultSetType = resultSetType;
	}

	// Running.

	@Override
	public boolean execute(String sql) throws SQLException {
		return run(sql, null);
	}

	@Override
	public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
		return run(sql, autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS ? new String[0] : null);
	}

	@Override
	public boolean execute(String sql, String[] columnNames) throws SQLException {
		return run(sql, columnNames);
	}

	@Override
	public ResultSet executeQuery(String sql) throws SQLException {
		run(sql, null);
		return rows();
	}

	@Override
	public int executeUpdate(String sql) throws SQLException {
		run(sql, null);
		return (int) count();
	}

	@Override
	public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
		execute(sql, autoGeneratedKeys);
		return (int) count();
	}

	@Override
	public int executeUpdate(String sql, String[] columnNames) throws SQLException {
		run(sql, columnNames);
		return (int) count();
	}

	@Override
	public long executeLargeUpdate(String sql) throws SQLException {
		run(sql, null);
		return count();
	}

	@Override
	public long executeLargeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
		execute(sql, autoGeneratedKeys);
		return count();
	}

	@Override
	public long executeLargeUpdate(String sql, String[] columnNames) throws SQLException {
		run(sql, columnNames);
		return count();
	}

	// keyColumns: null when the rows written are not asked for, empty for all their
	// columns.
	private boolean run(String sql, String @Nullable [] keyColumns) throws SQLException {
		if (sql == null) {
			throw new SQLException("The statement is null", "42601");
		}
		textual();
		Session session = begin();
		Sql written = null;
		Sql answering = null;
		if (keyColumns != null) {
			written = Sql.parse(sql, false);
			answering = written.answering(keyColumns);
		}
		synchronized (session) {
			ahead(session);
			session.simple(answering != null ? answering.text : sql);
			try {
				session.run(this.results, this.maxRows, this.timeoutSeconds > 0);
			}
			finally {
				this.warnings = session.takeWarnings();
			}
		}
		return settle(answering != written);
	}

	// Writes what has to hold while a statement runs: the limit on its time, and the
	// transaction it is of when the connection does not commit each statement.
	final void ahead(Session session) throws SQLException {
		session.limit(this.timeoutSeconds * 1000);
		if (!this.connection.getAutoCommit()) {
			session.transaction();
		}
	}

	// A member taking a statement's text was called: a prepared statement has its own.
	void textual() throws SQLException {
	}

	/** Starts a run: what the last one answered is closed and forgotten. */
	final Session begin() throws SQLException {
		open();
		if (this.resultSet != null) {
			this.resultSet.close();
		}
		this.resultSet = null;
		this.results.clear();
		this.current = 0;
		this.keys = null;
		this.warnings = null;
		return this.connection.session();
	}

	/**
	 * Ends a run.
	 * @param answered whether the rows of the results are the rows written, asked for
	 * @return whether the first result is rows
	 */
	final boolean settle(boolean answered) {
		if (answered) {
			for (int i = 0; i < this.results.size(); i++) {
				Result result = this.results.get(i);
				if (result.columns != null) {
					if (this.keys == null) {
						this.keys = new Result(result.columns);
					}
					this.keys.rows.addAll(result.rows);
					Result counted = new Result(null);
					counted.tag = result.tag;
					this.results.set(i, counted);
				}
			}
		}
		return !this.results.isEmpty() && this.results.get(0).columns != null;
	}

	final ResultSet rows() throws SQLException {
		ResultSet rows = getResultSet();
		if (rows == null) {
			throw new SQLException("The statement answered no rows", "02000");
		}
		return rows;
	}

	final long count() throws SQLException {
		if (this.current < this.results.size() && this.results.get(this.current).columns != null) {
			throw new SQLException("The statement answered rows where a count was asked for", "0100E");
		}
		return Math.max(getLargeUpdateCount(), 0);
	}

	// What a run answered.

	@Override
	public @Nullable ResultSet getResultSet() throws SQLException {
		open();
		if (this.current >= this.results.size() || this.results.get(this.current).columns == null) {
			return null;
		}
		if (this.resultSet == null) {
			this.resultSet = new PostgresResultSet(this, this.connection, this.results.get(this.current),
					this.resultSetType);
		}
		return this.resultSet;
	}

	@Override
	public int getUpdateCount() throws SQLException {
		return (int) Math.min(getLargeUpdateCount(), Integer.MAX_VALUE);
	}

	@Override
	public long getLargeUpdateCount() throws SQLException {
		open();
		if (this.current >= this.results.size() || this.results.get(this.current).columns != null) {
			return -1;
		}
		return this.results.get(this.current).count();
	}

	@Override
	public boolean getMoreResults() throws SQLException {
		return getMoreResults(Statement.CLOSE_CURRENT_RESULT);
	}

	@Override
	public boolean getMoreResults(int kept) throws SQLException {
		open();
		if (this.resultSet != null && kept != Statement.KEEP_CURRENT_RESULT) {
			this.resultSet.close();
		}
		this.resultSet = null;
		if (this.current < this.results.size()) {
			this.current++;
		}
		return this.current < this.results.size() && this.results.get(this.current).columns != null;
	}

	@Override
	public ResultSet getGeneratedKeys() throws SQLException {
		open();
		return new PostgresResultSet(null, this.connection, this.keys != null ? this.keys : new Result(new Column[0]),
				ResultSet.TYPE_FORWARD_ONLY);
	}

	// A result set of this statement was closed.
	final void closed(PostgresResultSet rows) throws SQLException {
		if (this.closeOnCompletion && rows == this.resultSet && this.current + 1 >= this.results.size()) {
			close();
		}
	}

	// A batch.

	@Override
	public void addBatch(String sql) throws SQLException {
		open();
		textual();
		this.batch.add(sql);
	}

	@Override
	public void clearBatch() throws SQLException {
		open();
		this.batch.clear();
	}

	@Override
	public int[] executeBatch() throws SQLException {
		long[] counts = executeLargeBatch();
		int[] narrowed = new int[counts.length];
		for (int i = 0; i < counts.length; i++) {
			narrowed[i] = (int) counts[i];
		}
		return narrowed;
	}

	/**
	 * Runs the batch in one piece: every command is written, then every answer read, a
	 * command the server refused being {@link Statement#EXECUTE_FAILED} among the counts.
	 */
	@Override
	public long[] executeLargeBatch() throws SQLException {
		Session session = begin();
		long[] counts = new long[this.batch.size()];
		if (counts.length == 0) {
			return counts;
		}
		SQLException refused = null;
		synchronized (session) {
			ahead(session);
			for (String sql : this.batch) {
				session.simple(sql);
			}
			this.batch.clear();
			try {
				List<Result> answered = new ArrayList<>();
				for (int i = 0; i < counts.length; i++) {
					answered.clear();
					SQLException one = session.group(answered, 0, this.timeoutSeconds > 0);
					counts[i] = one != null ? Statement.EXECUTE_FAILED
							: answered.isEmpty() ? 0 : answered.get(0).count();
					refused = refused != null ? refused : one;
				}
			}
			finally {
				this.warnings = session.takeWarnings();
			}
		}
		if (refused != null) {
			throw new BatchUpdateException(refused.getMessage(), refused.getSQLState(), 0, counts, refused);
		}
		return counts;
	}

	// The statement itself.

	@Override
	public void close() throws SQLException {
		if (!this.closed) {
			this.closed = true;
			if (this.resultSet != null) {
				this.resultSet.close();
			}
			this.resultSet = null;
			this.results.clear();
			this.keys = null;
		}
	}

	@Override
	public boolean isClosed() throws SQLException {
		return this.closed || this.connection.isClosed();
	}

	final void open() throws SQLException {
		if (isClosed()) {
			throw Failures.closed("statement");
		}
	}

	/**
	 * Asks the server to cancel what the connection is running; the statement cancelled
	 * ends with the server's refusal.
	 */
	@Override
	public void cancel() throws SQLException {
		open();
		this.connection.session().cancel();
	}

	@Override
	public Connection getConnection() throws SQLException {
		open();
		return this.connection;
	}

	@Override
	public @Nullable SQLWarning getWarnings() throws SQLException {
		open();
		return this.warnings;
	}

	@Override
	public void clearWarnings() throws SQLException {
		open();
		this.warnings = null;
	}

	final void warnings(@Nullable SQLWarning taken) {
		this.warnings = taken;
	}

	@Override
	public int getMaxRows() throws SQLException {
		open();
		return this.maxRows;
	}

	@Override
	public void setMaxRows(int max) throws SQLException {
		open();
		if (max < 0) {
			throw new SQLException("The most rows cannot be negative: " + max, "22023");
		}
		this.maxRows = max;
	}

	final int maxRows() {
		return this.maxRows;
	}

	@Override
	public long getLargeMaxRows() throws SQLException {
		return getMaxRows();
	}

	@Override
	public void setLargeMaxRows(long max) throws SQLException {
		setMaxRows((int) Math.min(max, Integer.MAX_VALUE));
	}

	/** The seconds a statement may run; the server ends one that runs longer. */
	@Override
	public int getQueryTimeout() throws SQLException {
		open();
		return this.timeoutSeconds;
	}

	@Override
	public void setQueryTimeout(int seconds) throws SQLException {
		open();
		if (seconds < 0 || seconds > Integer.MAX_VALUE / 1000) {
			throw new SQLException("The limit is no count of seconds a statement can run: " + seconds, "22023");
		}
		this.timeoutSeconds = seconds;
	}

	final int timeoutSeconds() {
		return this.timeoutSeconds;
	}

	@Override
	public int getFetchSize() throws SQLException {
		open();
		return this.fetchSize;
	}

	/** A hint: every row is read with its result whatever is asked for. */
	@Override
	public void setFetchSize(int rows) throws SQLException {
		open();
		if (rows < 0) {
			throw new SQLException("The rows to fetch cannot be negative: " + rows, "22023");
		}
		this.fetchSize = rows;
	}

	@Override
	public int getFetchDirection() throws SQLException {
		open();
		return ResultSet.FETCH_FORWARD;
	}

	@Override
	public void setFetchDirection(int direction) throws SQLException {
		open();
	}

	@Override
	public int getMaxFieldSize() throws SQLException {
		open();
		return 0;
	}

	@Override
	public void setMaxFieldSize(int max) throws SQLException {
		open();
		if (max != 0) {
			throw Failures.unsupported("A limit on the size of a value");
		}
	}

	/**
	 * The JDBC escapes in braces are not read: a statement goes to the server as it is.
	 */
	@Override
	public void setEscapeProcessing(boolean enable) throws SQLException {
		open();
	}

	@Override
	public int getResultSetType() throws SQLException {
		open();
		return this.resultSetType;
	}

	@Override
	public int getResultSetConcurrency() throws SQLException {
		open();
		return ResultSet.CONCUR_READ_ONLY;
	}

	@Override
	public int getResultSetHoldability() throws SQLException {
		open();
		return ResultSet.HOLD_CURSORS_OVER_COMMIT;
	}

	@Override
	public boolean isPoolable() throws SQLException {
		open();
		return this.poolable;
	}

	@Override
	public void setPoolable(boolean poolable) throws SQLException {
		open();
		this.poolable = poolable;
	}

	@Override
	public void closeOnCompletion() throws SQLException {
		open();
		this.closeOnCompletion = true;
	}

	@Override
	public boolean isCloseOnCompletion() throws SQLException {
		open();
		return this.closeOnCompletion;
	}

}
