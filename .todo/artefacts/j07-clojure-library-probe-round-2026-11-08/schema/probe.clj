(ns probe (:require [schema.core :as s]))
(s/defschema Person {:name s/Str :age s/Int (s/optional-key :email) s/Str})
(prn (s/validate Person {:name "a" :age 3}))
(prn (s/check Person {:name "a" :age "x"}))
(prn (s/check Person {:name 1}))
(prn (s/check [s/Int] [1 2 "3"]))
(prn (s/check (s/enum :a :b) :c))
(prn (s/check (s/maybe s/Keyword) nil))
(prn (s/explain Person))
(s/defn add :- s/Int [a :- s/Int b :- s/Int] (+ a b))
(prn (add 1 2))
(prn (s/with-fn-validation (try (add 1 "x") (catch Exception e (:type (ex-data e))))))
(prn (s/check (s/both s/Int (s/pred pos? 'pos?)) -1))
