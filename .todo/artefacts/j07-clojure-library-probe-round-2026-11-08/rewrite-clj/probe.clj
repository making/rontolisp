(ns probe (:require [rewrite-clj.zip :as z] [rewrite-clj.parser :as p] [rewrite-clj.node :as n]))
(def src "(defn foo [x]\n  ;; comment\n  (+ x 1))")
(def zloc (z/of-string src))
(prn (z/sexpr zloc))
(prn (-> zloc z/down z/right z/sexpr))
(prn (-> zloc z/down z/right (z/edit #(symbol (str % "-bar"))) z/root-string))
(prn (-> zloc (z/find-value z/next '+) (z/replace '-) z/root-string))
(prn (n/string (p/parse-string "{:a 1, :b [2 3]}")))
(prn (n/tag (p/parse-string "#{1 2}")))
(prn (-> (z/of-string "[1 2 3]") z/down z/rightmost (z/insert-right 4) z/root-string))
(prn (map z/sexpr (take-while (complement z/end?) (iterate z/next (z/of-string "(a (b c))")))))
(prn (n/string (n/coerce {:x [1 "s"]})))
