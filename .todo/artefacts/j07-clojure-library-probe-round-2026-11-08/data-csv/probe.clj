(ns probe (:require [clojure.data.csv :as csv] [clojure.java.io :as io]))
(prn (csv/read-csv "a,b,c\n1,2,3\n"))
(prn (doall (csv/read-csv "x,\"y,z\",\"q\"\"r\"\r\n4,5,6")))
(prn (doall (csv/read-csv "a;b\n1;2" :separator \;)))
(def w (java.io.StringWriter.))
(csv/write-csv w [["a" "b,c"] ["1" "say \"hi\""]])
(prn (str w))
(def w2 (java.io.StringWriter.))
(csv/write-csv w2 [["a" "b"]] :newline :cr+lf)
(prn (str w2))
(prn (with-open [r (io/reader (java.io.StringReader. "h1,h2\nv1,v2"))] (doall (csv/read-csv r))))
