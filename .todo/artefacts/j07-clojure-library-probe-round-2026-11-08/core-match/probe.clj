(prn (match [5] [(n :guard even?)] :even [n] [:odd n]))
(prn (map #(match [(mod % 3) (mod % 5)] [0 0] "FizzBuzz" [0 _] "Fizz" [_ 0] "Buzz" :else %) (range 1 16)))
