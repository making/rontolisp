package am.ik.jdbc.spin.postgres;

import java.sql.BatchUpdateException;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import org.jspecify.annotations.Nullable;

/**
 * A statement whose text goes to the host as it is: one command, since the host runs each
 * text as a prepared statement of the server's. The host answers rows or a count as it is
 * asked: {@code executeQuery} asks for the rows, {@code executeUpdate} for the count, and
 * {@code execute} tells which by the statement's words.
 */
class SpinPostgresStatement extends UnsupportedStatement {

	// What a run asks the host for.
	static final int ROWS = 0;

	static final int COUNT = 1;

	static final int EITHER = 2;

	private static final Postgres.RowSet NO_ROWS = new Postgres.RowSet(List.of(), List.of());

	final SpinPostgresConnection connection;

	private final int resultSetType;

	private boolean closed;

	// What the last run answered; null before a run and once getMoreResults went past
	// it.
	private @Nullable Result result;

	// The result set made of the result, once asked for.
	private @Nullable SpinPostgresResultSet resultSet;

	// The rows the last run wrote, when they were asked for.
	private Postgres.@Nullable RowSet keys;

	private int maxRows;

	private int fetchSize;

	private int timeoutSeconds;

	private boolean closeOnCompletion;

	private boolean poolable;

	private final List<String> batch = new ArrayList<>();

	SpinPostgresStatement(SpinPostgresConnection connection, int resultSetType) {
		this.connection = connection;
		this.resultSetType = resultSetType;
	}

	// Running.

	@Override
	public boolean execute(String sql) throws SQLException {
		return run(sql, null, EITHER);
	}

	@Override
	public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
		return run(sql, autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS ? new String[0] : null, EITHER);
	}

	@Override
	public boolean execute(String sql, String[] columnNames) throws SQLException {
		return run(sql, columnNames, EITHER);
	}

	@Override
	public ResultSet executeQuery(String sql) throws SQLException {
		run(sql, null, ROWS);
		return rows();
	}

	@Override
	public int executeUpdate(String sql) throws SQLException {
		return (int) executeLargeUpdate(sql);
	}

	@Override
	public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
		return (int) executeLargeUpdate(sql, autoGeneratedKeys);
	}

	@Override
	public int executeUpdate(String sql, String[] columnNames) throws SQLException {
		return (int) executeLargeUpdate(sql, columnNames);
	}

	@Override
	public long executeLargeUpdate(String sql) throws SQLException {
		run(sql, null, COUNT);
		return count();
	}

	@Override
	public long executeLargeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
		run(sql, autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS ? new String[0] : null, COUNT);
		return count();
	}

	@Override
	public long executeLargeUpdate(String sql, String[] columnNames) throws SQLException {
		run(sql, columnNames, COUNT);
		return count();
	}

	// keyColumns: null when the rows written are not asked for, empty for all their
	// columns.
	private boolean run(String sql, String @Nullable [] keyColumns, int asked) throws SQLException {
		if (sql == null) {
			throw new SQLException("The statement is null", "42601");
		}
		textual();
		begin();
		return run(Sql.parse(sql, false), keyColumns, null, List.of(), asked);
	}

	/**
	 * Runs a text and keeps what it answered.
	 * @param keyColumns the columns of the rows written to answer, or {@code null}
	 * @param types each parameter's type, or {@code null} for a text with none
	 * @param asked {@link #ROWS}, {@link #COUNT} or {@link #EITHER}
	 * @return whether the result is rows
	 */
	final boolean run(Sql written, String @Nullable [] keyColumns, @Nullable String @Nullable [] types,
			List<Postgres.ParameterValue> parameters, int asked) throws SQLException {
		Sql sql = keyColumns != null ? written.answering(keyColumns) : written;
		boolean answering = sql != written;
		boolean rows = answering || asked == ROWS || (asked == EITHER && sql.rows());
		Result answered = this.connection.run(sql.text(types), parameters, rows, this.timeoutSeconds, written.begins());
		Postgres.RowSet set = answered.rows;
		if (set == null) {
			this.result = answered;
		}
		else if (answering) {
			this.keys = set;
			this.result = new Result(set.rows().size());
		}
		else if (set.columns().isEmpty()) {
			// The statement answers no rows, whatever was asked or its words told, and
			// the host told no count.
			this.result = new Result(0);
		}
		else {
			this.result = new Result(this.maxRows > 0 && set.rows().size() > this.maxRows
					? new Postgres.RowSet(set.columns(), set.rows().subList(0, this.maxRows)) : set);
		}
		return this.result.rows != null;
	}

	/** The rows the last run wrote, when they were asked for. */
	final Postgres.@Nullable RowSet keys() {
		return this.keys;
	}

	// The rows a batch wrote: every run's, under the columns of the first.
	final void keys(List<Postgres.RowSet> written) {
		if (!written.isEmpty()) {
			List<List<Postgres.DbValue>> rows = new ArrayList<>();
			for (Postgres.RowSet each : written) {
				rows.addAll(each.rows());
			}
			this.keys = new Postgres.RowSet(written.get(0).columns(), rows);
		}
	}

	// Forgets what the last run answered, the rows written aside.
	final void forget() {
		this.result = null;
	}

	// A member taking a statement's text was called: a prepared statement has its own.
	void textual() throws SQLException {
	}

	/** Starts a run: what the last one answered is closed and forgotten. */
	final void begin() throws SQLException {
		open();
		if (this.resultSet != null) {
			this.resultSet.close();
		}
		this.resultSet = null;
		this.result = null;
		this.keys = null;
	}

	final ResultSet rows() throws SQLException {
		ResultSet rows = getResultSet();
		if (rows == null) {
			throw new SQLException("The statement answered no rows", "02000");
		}
		return rows;
	}

	final long count() throws SQLException {
		return Math.max(getLargeUpdateCount(), 0);
	}

	// What a run answered.

	@Override
	public @Nullable ResultSet getResultSet() throws SQLException {
		open();
		Postgres.RowSet rows = this.result != null ? this.result.rows : null;
		if (rows == null) {
			return null;
		}
		if (this.resultSet == null) {
			this.resultSet = new SpinPostgresResultSet(this, rows, this.resultSetType);
		}
		return this.resultSet;
	}

	@Override
	public int getUpdateCount() throws SQLException {
		return (int) Math.min(getLargeUpdateCount(), Integer.MAX_VALUE);
	}

	@Override
	public long getLargeUpdateCount() throws SQLException {
		open();
		Result answered = this.result;
		return answered == null || answered.rows != null ? -1 : answered.count;
	}

	@Override
	public boolean getMoreResults() throws SQLException {
		return getMoreResults(Statement.CLOSE_CURRENT_RESULT);
	}

	/** A statement is one command and answers one result: there is never another. */
	@Override
	public boolean getMoreResults(int kept) throws SQLException {
		open();
		if (this.resultSet != null && kept != Statement.KEEP_CURRENT_RESULT) {
			this.resultSet.close();
		}
		this.resultSet = null;
		this.result = null;
		return false;
	}

	@Override
	public ResultSet getGeneratedKeys() throws SQLException {
		open();
		return new SpinPostgresResultSet(null, this.keys != null ? this.keys : NO_ROWS, ResultSet.TYPE_FORWARD_ONLY);
	}

	// A result set of this statement was closed.
	final void closed(SpinPostgresResultSet rows) throws SQLException {
		if (this.closeOnCompletion && rows == this.resultSet) {
			close();
		}
	}

	// A batch.

	@Override
	public void addBatch(String sql) throws SQLException {
		open();
		textual();
		this.batch.add(sql);
	}

	@Override
	public void clearBatch() throws SQLException {
		open();
		this.batch.clear();
	}

	@Override
	public int[] executeBatch() throws SQLException {
		long[] counts = executeLargeBatch();
		int[] narrowed = new int[counts.length];
		for (int i = 0; i < counts.length; i++) {
			narrowed[i] = (int) counts[i];
		}
		return narrowed;
	}

	/**
	 * Runs the batch a command at a time, each asked for its count; a command the server
	 * refused is {@link Statement#EXECUTE_FAILED} among the counts, and the ones after it
	 * run.
	 */
	@Override
	public long[] executeLargeBatch() throws SQLException {
		begin();
		long[] counts = new long[this.batch.size()];
		SQLException refused = null;
		for (int i = 0; i < counts.length; i++) {
			try {
				run(Sql.parse(this.batch.get(i), false), null, null, List.of(), COUNT);
				counts[i] = count();
			}
			catch (SQLException ex) {
				counts[i] = Statement.EXECUTE_FAILED;
				refused = refused != null ? refused : ex;
			}
		}
		this.batch.clear();
		this.result = null;
		if (refused != null) {
			throw new BatchUpdateException(refused.getMessage(), refused.getSQLState(), 0, counts, refused);
		}
		return counts;
	}

	// The statement itself.

	@Override
	public void close() throws SQLException {
		if (!this.closed) {
			this.closed = true;
			if (this.resultSet != null) {
				this.resultSet.close();
			}
			this.resultSet = null;
			this.result = null;
			this.keys = null;
		}
	}

	@Override
	public boolean isClosed() throws SQLException {
		return this.closed || this.connection.isClosed();
	}

	final void open() throws SQLException {
		if (isClosed()) {
			throw Failures.closed("statement");
		}
	}

	/** The host's call cannot be reached while it runs: nothing cancels a statement. */
	@Override
	public void cancel() throws SQLException {
		open();
		throw Failures.unsupported("Statement.cancel (the host has no call that cancels a statement)");
	}

	@Override
	public Connection getConnection() throws SQLException {
		open();
		return this.connection;
	}

	/** The host hands over none of the server's notices. */
	@Override
	public @Nullable SQLWarning getWarnings() throws SQLException {
		open();
		return null;
	}

	@Override
	public void clearWarnings() throws SQLException {
		open();
	}

	@Override
	public int getMaxRows() throws SQLException {
		open();
		return this.maxRows;
	}

	/** The host hands over every row: the ones past the most are dropped here. */
	@Override
	public void setMaxRows(int max) throws SQLException {
		open();
		if (max < 0) {
			throw new SQLException("The most rows cannot be negative: " + max, "22023");
		}
		this.maxRows = max;
	}

	@Override
	public long getLargeMaxRows() throws SQLException {
		return getMaxRows();
	}

	@Override
	public void setLargeMaxRows(long max) throws SQLException {
		setMaxRows((int) Math.min(max, Integer.MAX_VALUE));
	}

	/** The seconds a statement may run; the server ends one that runs longer. */
	@Override
	public int getQueryTimeout() throws SQLException {
		open();
		return this.timeoutSeconds;
	}

	@Override
	public void setQueryTimeout(int seconds) throws SQLException {
		open();
		if (seconds < 0 || seconds > Integer.MAX_VALUE / 1000) {
			throw new SQLException("The limit is no count of seconds a statement can run: " + seconds, "22023");
		}
		this.timeoutSeconds = seconds;
	}

	@Override
	public int getFetchSize() throws SQLException {
		open();
		return this.fetchSize;
	}

	/** A hint: every row is handed over with its result whatever is asked for. */
	@Override
	public void setFetchSize(int rows) throws SQLException {
		open();
		if (rows < 0) {
			throw new SQLException("The rows to fetch cannot be negative: " + rows, "22023");
		}
		this.fetchSize = rows;
	}

	@Override
	public int getFetchDirection() throws SQLException {
		open();
		return ResultSet.FETCH_FORWARD;
	}

	@Override
	public void setFetchDirection(int direction) throws SQLException {
		open();
	}

	@Override
	public int getMaxFieldSize() throws SQLException {
		open();
		return 0;
	}

	@Override
	public void setMaxFieldSize(int max) throws SQLException {
		open();
		if (max != 0) {
			throw Failures.unsupported("A limit on the size of a value");
		}
	}

	/**
	 * The JDBC escapes in braces are not read: a statement goes to the server as it is.
	 */
	@Override
	public void setEscapeProcessing(boolean enable) throws SQLException {
		open();
	}

	@Override
	public int getResultSetType() throws SQLException {
		open();
		return this.resultSetType;
	}

	@Override
	public int getResultSetConcurrency() throws SQLException {
		open();
		return ResultSet.CONCUR_READ_ONLY;
	}

	@Override
	public int getResultSetHoldability() throws SQLException {
		open();
		return ResultSet.HOLD_CURSORS_OVER_COMMIT;
	}

	@Override
	public boolean isPoolable() throws SQLException {
		open();
		return this.poolable;
	}

	@Override
	public void setPoolable(boolean poolable) throws SQLException {
		open();
		this.poolable = poolable;
	}

	@Override
	public void closeOnCompletion() throws SQLException {
		open();
		this.closeOnCompletion = true;
	}

	@Override
	public boolean isCloseOnCompletion() throws SQLException {
		open();
		return this.closeOnCompletion;
	}

}
